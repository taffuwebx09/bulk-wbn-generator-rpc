import "dotenv/config";
import express from "express";
import fs from "node:fs";
import path from "node:path";
import cors from "cors";
import { randomUUID } from "node:crypto";
import { createAccessToken, verifyAccessToken, isPaired, pairingCodeFile } from "./auth.js";
import { store } from "./db.js";
import { appendCsv, buildFinalCsv, finalFile } from "./merge.js";
import { splitIntoBatches } from "./batching.js";

const MAX_BATCH = 15000;
const MAX_WBNS = 2500000;
const allowedOrigins = new Set([
  "http://localhost:5173", "http://127.0.0.1:5173", "http://192.168.1.2:5173",
  "https://bulk-wbn-generator-rpc.vercel.app",
  ...(process.env.DASHBOARD_ORIGINS || "").split(",").map((x) => x.trim()).filter(Boolean)
]);
const app = express();
app.disable("x-powered-by");
app.use((req, res, next) => {
  // Chrome may send this preflight header when an HTTPS dashboard contacts loopback.
  if (req.get("access-control-request-private-network") === "true") {
    res.setHeader("Access-Control-Allow-Private-Network", "true");
  }
  next();
});
app.use(cors({
  origin(origin, callback) {
    if (!origin || allowedOrigins.has(origin) || origin.startsWith("chrome-extension://")) return callback(null, true);
    return callback(new Error(`Origin not allowed: ${origin}`));
  },
  maxAge: 600
}));
app.use(express.json({ limit: "128mb" }));

const findJob = (id) => store.jobs.find((j) => j.id === id);
const findBatch = (id, n) => store.batches.find((b) => b.jobId === id && b.batchNumber === Number(n));
const publicJob = (j) => ({ ...j });
const error = (res, status, message) => res.status(status).json({ ok: false, error: message });

app.get("/api/health", (_req, res) => res.json({ ok: true, service: "bulk-wbn-api", paired: isPaired(), time: new Date().toISOString() }));
const pairAttempts = new Map();
app.post("/api/pair", (req, res) => {
  const now = Date.now();
  const ip = req.ip || req.socket.remoteAddress || "unknown";
  const attempt = pairAttempts.get(ip) || { count: 0, since: now };
  if (now - attempt.since > 15 * 60 * 1000) { attempt.count = 0; attempt.since = now; }
  attempt.count += 1; pairAttempts.set(ip, attempt);
  if (attempt.count > 8) return error(res, 429, "Too many pairing attempts. Wait 15 minutes and try again.");
  const accessToken = createAccessToken(req.body?.pairingCode);
  if (!accessToken) return error(res, 401, "Pairing code is incorrect. Open the Local Processor pairing-code.txt file and try again.");
  pairAttempts.delete(ip);
  res.json({ ok: true, accessToken });
});
app.use("/api", (req, res, next) => {
  if (req.path === "/health" || req.path === "/pair") return next();
  const header = req.get("authorization") || "";
  const token = header.startsWith("Bearer ") ? header.slice(7) : "";
  if (!verifyAccessToken(token)) return error(res, 401, "Local Backend is not paired. Connect using the pairing code first.");
  next();
});

// Clear dashboard history, persisted backend records, and generated report files.
app.delete("/api/data", (_req, res) => {
  try {
    const outputDir = path.resolve(process.env.DOWNLOADS_DIR || "downloads");
    if (fs.existsSync(outputDir)) {
      for (const name of fs.readdirSync(outputDir)) {
        // Only remove files generated by this application; never recurse into folders.
        if (/^[a-zA-Z0-9_-]+(?:\.csv|\.batch-\d{4}\.csv|\.csv\.[\w.-]+\.tmp|\.batch-\d{4}\.csv\.[\w.-]+\.tmp)$/.test(name)) {
          const target = path.join(outputDir, name);
          if (fs.statSync(target).isFile()) fs.rmSync(target, { force: true });
        }
      }
    }
    store.clear();
    res.json({ ok: true, message: "All backend job data and generated CSV files were cleared." });
  } catch (e) {
    error(res, 500, `Could not clear all backend data: ${e.message}`);
  }
});
app.get("/api/jobs", (_req, res) => res.json({ jobs: store.jobs.map(publicJob) }));
app.post("/api/jobs", (req, res) => {
  const { remarks, reportOption = "Default", wbns } = req.body || {};
  if (typeof remarks !== "string" || !remarks.trim()) return error(res, 400, "Remarks are required");
  if (!Array.isArray(wbns) || !wbns.length) return error(res, 400, "At least one WBN is required");
  if (wbns.length > MAX_WBNS) return error(res, 400, `Maximum input is ${MAX_WBNS.toLocaleString("en-IN")} WBNs`);
  if (typeof reportOption !== "string" || !reportOption.trim()) return error(res, 400, "Invalid report option");
  const cleaned = [];
  const seen = new Set();
  let blankCount = 0, duplicateCount = 0;
  for (const value of wbns) {
    if (typeof value !== "string") return error(res, 400, "Each WBN must be text; numeric JSON values can lose leading zeros");
    const wbn = String(value).trim();
    if (!wbn) { blankCount++; continue; }
    if (!/^[A-Za-z0-9-]+$/.test(wbn)) return error(res, 400, `Unsupported characters in WBN: ${wbn.slice(0, 40)}`);
    if (seen.has(wbn)) { duplicateCount++; continue; }
    seen.add(wbn); cleaned.push(wbn);
  }
  if (!cleaned.length) return error(res, 400, "No valid WBNs remain after removing blank lines");
  const chunks = splitIntoBatches(cleaned, MAX_BATCH);
  const id = randomUUID().replaceAll("-", "").slice(0, 12);
  const job = {
    id, remarks: remarks.trim(), reportOption: reportOption.trim(),
    totalWbns: cleaned.length, inputWbns: wbns.length, blankCount, duplicateCount,
    totalBatches: chunks.length, completedBatches: 0, currentBatch: 0,
    status: "queued", downloadUrl: null, error: null,
    lastRpcReportFound: false, lastRpcReportStatus: null, lastRpcRemark: null,
    lastRpcCheckedAt: null, createdAt: new Date().toISOString(), updatedAt: new Date().toISOString()
  };
  store.jobs.unshift(job);
  chunks.forEach((values, i) => store.batches.push({
    jobId: id, batchNumber: i + 1, wbnCount: values.length, wbns: values,
    status: "queued", rpcRemarks: null, rpcReportId: null, submittedAt: null,
    lastPollingAt: null, retryCount: 0, reconcileAttempts: 0, error: null, csvAppend: null
  }));
  store.save();
  res.status(201).json({ job, policy: { blankLinesRemoved: blankCount, duplicatesRemoved: duplicateCount, caseSensitive: true, trimOuterWhitespace: true } });
});
app.get("/api/jobs/:id", (req, res) => {
  const job = findJob(req.params.id);
  if (!job) return error(res, 404, "Job not found");
  res.json({ job: publicJob(job), batches: store.batches.filter((b) => b.jobId === job.id).map(({ wbns, ...b }) => b) });
});
app.get("/api/jobs/:id/batches/:n", (req, res) => {
  const b = findBatch(req.params.id, req.params.n);
  if (!b) return error(res, 404, "Batch not found");
  res.json({ batch: b });
});
app.patch("/api/jobs/:id", (req, res) => {
  const job = findJob(req.params.id);
  if (!job) return error(res, 404, "Job not found");
  const allowed = ["status", "error", "currentBatch", "lastRpcReportFound", "lastRpcReportStatus", "lastRpcRemark", "lastRpcCheckedAt"];
  const patch = req.body || {};
  for (const key of Object.keys(patch)) if (!allowed.includes(key)) return error(res, 400, `Field cannot be updated here: ${key}`);
  if (patch.currentBatch !== undefined && (!Number.isInteger(patch.currentBatch) || patch.currentBatch < 0 || patch.currentBatch > job.totalBatches)) return error(res, 400, "Invalid currentBatch");
  if (patch.status !== undefined && !["queued", "running", "waiting", "error", "needs_attention", "cancelled"].includes(patch.status)) return error(res, 400, "Invalid job status");
  Object.assign(job, patch, { updatedAt: new Date().toISOString() });
  store.save(); res.json({ job });
});
app.patch("/api/jobs/:id/batches/:n", (req, res) => {
  const b = findBatch(req.params.id, req.params.n);
  if (!b) return error(res, 404, "Batch not found");
  const allowed = ["status", "rpcRemarks", "rpcReportId", "submittedAt", "lastPollingAt", "retryCount", "reconcileAttempts", "error"];
  const patch = req.body || {};
  for (const key of Object.keys(patch)) if (!allowed.includes(key)) return error(res, 400, `Field cannot be updated here: ${key}`);
  if (patch.status !== undefined && !["queued", "submitting", "submitted", "pending", "in_progress", "complete", "downloading", "merged", "completed", "failed", "needs_attention"].includes(patch.status)) return error(res, 400, "Invalid batch status");
  if (patch.retryCount !== undefined && (!Number.isInteger(patch.retryCount) || patch.retryCount < 0)) return error(res, 400, "Invalid retryCount");
  if (patch.reconcileAttempts !== undefined && (!Number.isInteger(patch.reconcileAttempts) || patch.reconcileAttempts < 0)) return error(res, 400, "Invalid reconcileAttempts");
  Object.assign(b, patch, { updatedAt: new Date().toISOString() });
  if (patch.status === "completed") {
    const job = findJob(req.params.id);
    job.completedBatches = store.batches.filter((item) => item.jobId === job.id && item.status === "completed" && item.csvAppend?.hash).length;
    job.updatedAt = new Date().toISOString();
  }
  store.save(); res.json({ batch: { ...b, wbns: undefined } });
});
app.post("/api/reports/append", (req, res) => {
  const { jobId, batchNo, csv } = req.body || {};
  const job = findJob(jobId);
  if (!job) return error(res, 404, "Job not found");
  const batch = findBatch(jobId, batchNo);
  if (!batch) return error(res, 404, "Batch not found");
  try {
    const result = appendCsv(jobId, batchNo, csv, store);
    res.json(result);
  } catch (e) { error(res, 400, e.message); }
});
app.post("/api/reports/finish/:id", async (req, res) => {
  const job = findJob(req.params.id);
  if (!job) return error(res, 404, "Job not found");
  try {
    const batches = store.batches.filter((b) => b.jobId === job.id);
    const result = await buildFinalCsv(job, batches, store);
    job.status = "completed";
    job.completedBatches = job.totalBatches;
    job.downloadUrl = `/api/jobs/${job.id}/download`;
    job.error = null;
    job.finalRows = result.rows;
    job.finalizedAt = new Date().toISOString();
    job.updatedAt = new Date().toISOString();
    store.save();
    res.json({ ok: true, download: job.downloadUrl, rows: result.rows, batches: result.batches, overflowRows: result.overflowRows, extraFields: result.extraFields, warnings: result.warnings });
  } catch (e) { error(res, 409, e.message); }
});
app.get("/api/jobs/:id/download", (req, res) => {
  const job = findJob(req.params.id);
  if (!job || job.status !== "completed" || !job.downloadUrl) return error(res, 404, "Final report is not ready yet");
  try {
    const file = finalFile(job.id);
    res.download(file, `bulk-wbn-${job.id}.csv`, (e) => {
      if (e && !res.headersSent) res.status(500).json({ error: "Could not send final CSV" });
    });
  } catch (e) { error(res, 404, e.message); }
});
app.use((err, _req, res, _next) => {
  const status = err.message?.startsWith("Origin not allowed") ? 403 : 500;
  res.status(status).json({ ok: false, error: err.message || "Internal server error" });
});

export { app };
